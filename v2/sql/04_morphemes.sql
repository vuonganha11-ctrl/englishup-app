CREATE TABLE IF NOT EXISTS morphemes (
  id          SERIAL PRIMARY KEY,
  morpheme    TEXT NOT NULL UNIQUE,
  type        TEXT NOT NULL CHECK (type IN ('prefix','suffix','root')),
  origin      TEXT NOT NULL CHECK (origin IN ('Latin','Greek','Germanic')),
  meaning_vi  TEXT NOT NULL,
  gloss_en    TEXT NOT NULL,
  rank        SMALLINT,
  note        TEXT
);
COMMENT ON TABLE  morphemes        IS 'Tiền tố / hậu tố / gốc từ — 24 prefix + 23 suffix + 60 root';
COMMENT ON COLUMN morphemes.rank   IS 'Thứ tự ưu tiên dạy trong mỗi loại (1 = dạy trước nhất)';

CREATE TABLE IF NOT EXISTS word_morphemes (
  word_id     BIGINT NOT NULL REFERENCES words(id)     ON DELETE CASCADE,
  morpheme_id INT    NOT NULL REFERENCES morphemes(id) ON DELETE CASCADE,
  PRIMARY KEY (word_id, morpheme_id)
);
CREATE INDEX IF NOT EXISTS wm_morpheme_idx ON word_morphemes (morpheme_id);
COMMENT ON TABLE word_morphemes IS
  'Liên kết từ <-> hình vị. Chỉ chứa liên kết ĐÃ DUYỆT TAY: 707 giữ / 1376 ứng viên máy sinh (49% bị loại).';

