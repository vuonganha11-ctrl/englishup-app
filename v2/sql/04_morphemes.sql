-- ─── View: cây từ theo hình vị ───────────────────────────────
CREATE OR REPLACE VIEW morpheme_tree AS
SELECT m.morpheme, m.type, m.origin, m.meaning_vi,
       count(w.id)                        AS so_tu,
       array_agg(w.term ORDER BY w.ngsl_rank) AS cac_tu
FROM morphemes m
JOIN word_morphemes wm ON wm.morpheme_id = m.id
JOIN words w           ON w.id = wm.word_id
GROUP BY m.id, m.morpheme, m.type, m.origin, m.meaning_vi;

